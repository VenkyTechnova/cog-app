def _r5(x: float) -> int:
    return int(round(x / 5.0) * 5)


def task_rows() -> list[dict]:
    rows = []
    for i, r in enumerate(RAW):
        (tid, sec, stage, name, freq, owner, cat, why, trig, act, deleg, sla, base, saved, wf) = r
        rows.append(
            dict(
                id=tid,
                playbook_section=sec,
                stage=stage,
                task_name=name,
                frequency=freq,
                current_owner=owner,
                category=cat,
                rationale=why,
                trigger=trig,
                automation_action=act,
                delegate_to=deleg,
                sla_hours=sla,
                baseline_minutes_per_week=max(5, _r5(base * BASE_SCALE)),
                est_minutes_saved_per_week=max(0, _r5(saved * SAVED_SCALE)) if saved else 0,
                status="live",
                workflow_key=wf,
                sort_order=i,
            )
        )
    return rows
